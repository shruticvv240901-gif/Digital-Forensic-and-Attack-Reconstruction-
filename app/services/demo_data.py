def filter_demo_events(
    events: List[Dict[str, Any]],
    event_id: str = "all",
    time_range: str = "-24h",
    limit: int = 50,
    reference_time: datetime = None
) -> List[Dict[str, Any]]:
    """
    Applies Event ID, time-range, and limit filters to the simulated demo dataset.
    Accurately emulates how Splunk SPL filters behave so the user can test the UI controls.
    """
    if reference_time is None:
        reference_time = datetime.now()

    filtered = list(events)

    # 1. Filter by Event ID
    if event_id and str(event_id).strip().lower() != "all":
        target_id = str(event_id).strip()
        filtered = [e for e in filtered if str(e.get("event_id")) == target_id]

    # 2. Filter by Time Range
    threshold_dt = None
    tr = str(time_range).strip().lower()
    if tr == "-15m":
        threshold_dt = reference_time - timedelta(minutes=15)
    elif tr == "-1h":
        threshold_dt = reference_time - timedelta(hours=1)
    elif tr == "-24h":
        threshold_dt = reference_time - timedelta(hours=24)
    elif tr == "-7d":
        threshold_dt = reference_time - timedelta(days=7)
    elif tr in ("0", "all", "all time"):
        threshold_dt = None

    if threshold_dt is not None:
        valid_events = []
        for e in filtered:
            try:
                ev_dt = datetime.strptime(e["timestamp"], "%Y-%m-%d %H:%M:%S")
                if ev_dt >= threshold_dt:
                    valid_events.append(e)
            except Exception:
                valid_events.append(e)
        filtered = valid_events

    # 3. Apply limit
    return filtered[:limit]
